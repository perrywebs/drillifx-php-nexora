    if (!csrf_check($_POST['csrf'] ?? null)) { flash('error','Security check','Invalid session. Try again.'); }
    else {
        $cur = $_POST['current_password'] ?? ''; $new = $_POST['new_password'] ?? ''; $cf = $_POST['confirm_password'] ?? '';
        $st = db()->prepare('SELECT password_hash FROM users WHERE id=?');
        $st->execute([(int)$u['id']]);
        $row = $st->fetch();
        if (!password_verify($cur, $row['password_hash'] ?? '')) flash('error','Change password','Current password is incorrect.');
        elseif (strlen($new) < 6) flash('error','Change password','New password must be at least 6 characters.');
        elseif ($new !== $cf) flash('error','Change password','New passwords do not match.');
        else {
            db()->prepare('UPDATE users SET password_hash=? WHERE id=?')->execute([password_hash($new, PASSWORD_DEFAULT), (int)$u['id']]);
            log_activity((int)$u['id'],'password','Password changed');
            notify((int)$u['id'],'Security alert','Your password was just changed.');
            send_template($u['email'], 'password_changed', user_email_vars($u), (int)$u['id']);
            flash('success','Password updated','Your password has been changed.');
        }
    }
    redirect('/users/change-password.php');
